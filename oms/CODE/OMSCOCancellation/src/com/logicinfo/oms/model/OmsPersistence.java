	private boolean isPOOrder(String customerNo, String items) {
		boolean hasPOOrder = false;
		Connection connection = null;
		PreparedStatement statement = null;
		ResultSet rs = null;
		try {
			connection = OMSUtil.createDBConnection(OMSConstants.DS_OMS_STRING);
			statement = connection.prepareStatement(CHECK_PO_ORDER_QUERY.replace(":item", items));
			statement.setString(1, customerNo);
			rs = statement.executeQuery();
			if (rs.next()) {
				hasPOOrder = rs.getInt(1) > 0;
			}
			log.info("is PO order for customerNo " + customerNo + " is " + hasPOOrder);
		} catch (Exception e) {
			log.warn("Issue while checking the order for fullfilment type PO", e);
		} finally {
			try {
				if (rs != null && !rs.isClosed()) {
					rs.close();
				}
			} catch (Exception e) {
			}
			try {
				if (statement != null && !statement.isClosed()) {
					statement.close();
				}
			} catch (Exception e) {
			}
			try {
				if (connection != null && !connection.isClosed()) {
					connection.close();
				}
			} catch (Exception e) {
			}
		}
		return hasPOOrder;
	}
