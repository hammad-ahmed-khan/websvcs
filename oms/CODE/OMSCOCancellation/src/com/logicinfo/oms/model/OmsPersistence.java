	public void persistOmsCoCancelHead(CustomerOrderCancellation input, BigDecimal omsCustOrderNo) throws SOAPException {
		OMSUtilSessionEJB session = OMSUtil.doLookup();
		log.info("**persistOmsCoCancelHead start**");
		try {
			OmsCoCancelHead omsCoCancelHead = new OmsCoCancelHead();
			omsCoCancelHead.setEntityId(input.getEntityId());
			omsCoCancelHead.setApplicationId(input.getApplicationId());
			omsCoCancelHead.setCustOrdNo((input.getCustOrderNo()));
			if (input.getSubCustOrderNo() == null) {
				omsCoCancelHead.setSubCustOrdNo("1");
			} else {
				omsCoCancelHead.setSubCustOrdNo((input.getSubCustOrderNo()));
			}
			omsCoCancelHead.setCancelReqstLocId(new BigDecimal(input.getCancellationRequestorId()));
			omsCoCancelHead.setCancelReqId(new BigDecimal(input.getCancellationId()));
			omsCoCancelHead.setRefundOption(input.getRefundPreference());
			Long requestorId = NumberUtils.toLong(input.getCancellationRequestorId());
			StringBuilder items = new StringBuilder();
			for (CustomerOrderCancellationItems item: input.getCancellationItems()) {
				if (items.length() > 0) {
					items.append(", ");
				}
				items.append('\'').append(item.getItem()).append('\'');
			}
			log.info("Requestor Id for the omsCustOrderNo -> " + omsCustOrderNo + " is " + requestorId);
			if (!"HybrisCancellation".equalsIgnoreCase(input.getComments()) && requestorId >= 20000 && requestorId < 30000 /* For BH */ && isPOOrder(input.getCustOrderNo(), items.toString())) {
				omsCoCancelHead.setRefundCompltInd("Z");
			} else if (input.getRefundPreference().equals("CLEARING")) {
				omsCoCancelHead.setRefundCompltInd("Y");
			} else {
				omsCoCancelHead.setRefundCompltInd("N");
			}
			omsCoCancelHead.setRefindAmount(input.getRefundAmount());
			omsCoCancelHead.setComments(input.getComments());
			omsCoCancelHead.setCanReqDatetime(new Timestamp(new Date().getTime()));
			omsCoCancelHead.setCreateDatetime(new Timestamp(new Date().getTime()));
			omsCoCancelHead.setStatus("N");
			session.persistOmsCoCancelHead(omsCoCancelHead);
			log.info("Successfully persisted into OmsCoCancelHead");
		} catch (Exception e) {
			String errString = OMSUtilCommons.formErrorDescription(OMSConstants.ERR_TABLE_INSERT, "1", new String[] { "oms_co_cancel_head" });
			log.error(errString, e);
			throw new SOAPException(errString);
		}
	}

