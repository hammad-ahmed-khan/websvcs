	private final static String CHECK_PO_ORDER_QUERY = "select count(*) from OMS_CO_FULFILL_DETAIL F, OMS_CUST_ORD_HEAD C, OMS_CO_CANCEL_REGION CR where F.OMS_CUST_ORD_NO = C.OMS_CUST_ORD_NO and F.SOURCE_LOC_TYPE = 'SU' AND C.STATUS = 'S' and CR.REQUESTOR_ID = C.ORDER_REQUESTOR_ID and C.CUST_ORDER_NO = ? AND F.ITEM IN (:item) ";

