package org.logicInfo.oms.transferCreation.Controller;

public class TransferRequest {
	private String item;
	private int qty;
	
	public String getItem() {
		return item;
	}
	public void setItem(String item) {
		this.item = item;
	}
	public int getQty() {
		return qty;
	}
	public void setQty(int qty) {
		this.qty = qty;
	}
	
	
}
