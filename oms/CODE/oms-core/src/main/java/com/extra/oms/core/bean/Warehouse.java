public class Warehouse {

	private Long wh;

	private String name;

	private Long physicalWH;

	public Long getWh() {
		return wh;
	}

	public void setWh(Long wh) {
		this.wh = wh;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public Long getPhysicalWH() {
		return physicalWH;
	}

	public void setPhysicalWH(Long physicalWH) {
		this.physicalWH = physicalWH;
	}
}
