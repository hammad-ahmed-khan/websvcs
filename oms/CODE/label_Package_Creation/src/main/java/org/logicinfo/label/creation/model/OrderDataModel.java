package org.logicinfo.label.creation.model;

public class OrderDataModel {
private String PieceBarcode,PieceWeight,PiecePrice,PieceDescription;

public String getPieceBarcode() {
	return PieceBarcode;
}

public void setPieceBarcode(String pieceBarcode) {
	PieceBarcode = pieceBarcode;
}

public String getPieceWeight() {
	return PieceWeight;
}

public void setPieceWeight(String pieceWeight) {
	PieceWeight = pieceWeight;
}

public String getPiecePrice() {
	return PiecePrice;
}

public void setPiecePrice(String piecePrice) {
	PiecePrice = piecePrice;
}

public String getPieceDescription() {
	return PieceDescription;
}

public void setPieceDescription(String pieceDescription) {
	PieceDescription = pieceDescription;
}

}
