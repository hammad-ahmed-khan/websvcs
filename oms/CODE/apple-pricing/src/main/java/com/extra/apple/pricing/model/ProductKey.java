public class ProductKey {

	private String lob;

	private String sublob;

	private String connectivity;

	private String caseSize;

	private String caseColor;

	private String caseType;
	
	private String bandColor;

	private String bandType;

	public String getLob() {
		return lob;
	}

	public void setLob(String lob) {
		this.lob = lob;
	}

	public String getSublob() {
		return sublob;
	}

	public void setSublob(String sublob) {
		this.sublob = sublob;
	}

	public String getConnectivity() {
		return connectivity;
	}

	public void setConnectivity(String connectivity) {
		this.connectivity = connectivity;
	}

	public String getCaseSize() {
		return caseSize;
	}

	public void setCaseSize(String caseSize) {
		this.caseSize = caseSize;
	}

	public String getCaseColor() {
		return caseColor;
	}

	public void setCaseColor(String caseColor) {
		this.caseColor = caseColor;
	}

	public String getCaseType() {
		return caseType;
	}

	public void setCaseType(String caseType) {
		this.caseType = caseType;
	}

	public String getBandColor() {
		return bandColor;
	}

	public void setBandColor(String bandColor) {
		this.bandColor = bandColor;
	}

	public String getBandType() {
		return bandType;
	}

	public void setBandType(String bandType) {
		this.bandType = bandType;
	}
}
